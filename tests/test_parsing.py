import pytest
from conftest import read

from scaps_mcp.parsing import (
    measurement_scales,
    parse_definition,
    parse_error_log,
    parse_material,
    parse_result,
    parse_spectrum,
)


def test_iv_metrics_and_table():
    result = parse_result(read("synthetic.iv"))
    assert result.kind == "I-V"
    assert result.metrics["Voc"] == pytest.approx(0.679598)
    assert result.metrics["eta"] == pytest.approx(20.9873)
    assert result.units["Jsc"] == "mA/cm2"
    table = result.table
    assert table.columns[:2] == ["v(V)", "jtot(mA/cm2)"]
    assert len(table.rows) == 21
    assert table.rows[0][0] == 0.0
    assert "v(V)" not in result.info
    assert result.info["Temperature"] == "300.00 K"


@pytest.mark.parametrize(
    ("name", "kind", "first_column", "rows"),
    [
        ("synthetic.qe", "QE", "lambda(nm)", 17),
        ("synthetic.cv", "C-V", "v(V)", 9),
        ("synthetic.cf", "C-f", "f(Hz)", 10),
    ],
)
def test_curve_files(name, kind, first_column, rows):
    result = parse_result(read(name))
    assert result.kind == kind
    assert result.table.columns[0] == first_column
    assert len(result.table.rows) == rows
    assert result.metrics == {}


def test_multiple_blocks_keep_last_table():
    result = parse_result(read("synthetic.iv") + "\n" + read("synthetic.qe"))
    assert len(result.tables) == 2
    assert result.table.columns[0] == "lambda(nm)"


def test_non_finite_values_become_none():
    result = parse_result("Simulation of QE curves\n\nlambda(nm)\tQE(%)\n400\t50\n500\tnan\n")
    assert result.table.rows == [[400.0, 50.0], [500.0, None]]


@pytest.mark.parametrize(
    ("header", "kind", "expected"),
    [
        ("cell area: 0.5 cm2\nunits: V: Volt ; I: mA\n", "iv", (1.0, 2.0)),
        ("area 25 mm2\nUnits: I: A V: mV\n", "iv", (1e-3, 4e3)),
        ("Units: C: pF  V: V\n", "cv", (1.0, 1e-3)),
        ("units: lambda: m    QE: 1\n", "qe", (1e9, 100.0)),
        ("temperature 300\n", "cf", (1.0, 1.0)),
    ],
)
def test_measurement_scales(header, kind, expected):
    assert measurement_scales(header + "0\t1\n1\t2\n", kind) == pytest.approx(expected)


def test_header_only_file_has_no_table():
    result = parse_result("SCAPS output generated by a script\nfilename\tx.script\n")
    assert result.table is None
    assert result.info == {"filename": "x.script"}


def test_definition_in_script_units():
    device = parse_definition(read("synthetic.def"))
    absorber, window = device["layers"]
    assert absorber["name"] == "absorber"
    assert absorber["thickness"] == pytest.approx(1.5)
    assert absorber["NA"] == pytest.approx(1e16)
    assert absorber["mun"] == pytest.approx(50)
    assert window["Eg"] == pytest.approx(2.4)
    defect = absorber["defects"][0]
    assert defect["Ntotal"] == pytest.approx(1e14)
    assert defect["capture_cross_section.electron"] == pytest.approx(1e-15)
    assert defect["Et_reference"] == "above Ei"
    interface = device["interfaces"][0]
    assert interface["layers"] == [1, 2]
    assert interface["defects"][0]["N"] == pytest.approx(1e10)
    assert interface["defects"][0]["N_unit"] == "cm^-2"
    assert device["contacts"]["left"]["Sn"] == pytest.approx(1e5)
    assert device["working_point"]["illuminated_from"] == "right"


def test_error_log():
    errors = parse_error_log(read("errors.log"))
    assert len(errors) == 4
    assert errors[0].command == "set layer1.defect.add_default"
    assert "no defects defined in layer 1" in errors[0].message


def test_scaps_written_definition_with_two_defects_per_section():
    device = parse_definition(read("seeded.def"))
    absorber = device["layers"][0]
    assert [d["Ntotal"] for d in absorber["defects"]] == pytest.approx([1e14, 1e12])
    assert absorber["defects"][0]["type"] == "acceptor"
    assert device["interfaces"][0]["defects"][0]["N"] == pytest.approx(1e10)
    assert device["sq_limit_mode"] == 0


def test_spatial_profiles():
    bands = parse_result(read("seeded.eb"))
    assert [t.title for t in bands.tables] == ["bulk", "interface"]
    assert bands.table.title == "bulk"
    assert bands.table.columns[:4] == ["i", "x(um)", "y", "Ec(eV)"]
    assert bands.info["Band diagramme at actual bias voltage"].startswith("0.3")
    genrec = parse_result(read("seeded.gen"))
    assert genrec.table.columns[1].startswith("x (")


def test_material_in_gui_units():
    material = parse_material(read("test.material"))
    assert material["properties"]["Eg"] == pytest.approx(1.4)
    assert material["properties"]["NC"] == pytest.approx(2e18)
    assert material["properties"]["mun"] == pytest.approx(50)
    assert material["absorption"] == {"file": "test film.abs"}


def test_spectrum_skips_comments():
    bins = parse_spectrum("> AM test\n>lambda\tP\n400\t1.5\n500\t2.5\n")
    assert bins == [(400.0, 1.5), (500.0, 2.5)]
